export function getWidgetTranslations(
  languageCode: SupportedLanguageCode,
  overrides?: Partial<Record<WidgetTranslationKey, string>>,
): Record<WidgetTranslationKey, string> {
  const base = WIDGET_TRANSLATIONS_BY_LANGUAGE[languageCode] ?? DEFAULT_WIDGET_TRANSLATIONS;

  return {
    ...base,
    ...Object.fromEntries(
      Object.entries(overrides ?? {}).filter(([, value]) => Boolean(value?.trim())),
    ),
  } as Record<WidgetTranslationKey, string>;
}

export function getPanelTranslations(
  languageCode: SupportedLanguageCode,
): Record<PanelTranslationKey, string> {
  return PANEL_TRANSLATIONS_BY_LANGUAGE[languageCode] ?? DEFAULT_PANEL_TRANSLATIONS;
}

export function interpolateTranslation(
  template: string,
  values: Record<string, string | number>,
): string {
  return Object.entries(values).reduce((message, [key, value]) => {
    return message.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value));
  }, template);
}
